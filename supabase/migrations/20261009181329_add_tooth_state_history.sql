SET search_path TO app, public;

-- Append-only clinical history; an absent row means "not recorded", not healthy.
CREATE TABLE IF NOT EXISTS tooth_state_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id INTEGER NOT NULL REFERENCES patients(id) ON DELETE CASCADE,
  tooth_number TEXT NOT NULL CHECK (tooth_number ~ '^([1-4][1-8]|[5-8][1-5])$'),
  presence TEXT NOT NULL CHECK (presence IN ('unknown', 'present', 'unerupted', 'exfoliated', 'extracted')),
  effective_date DATE NOT NULL,
  notes TEXT NOT NULL DEFAULT '' CHECK (length(notes) <= 1000),
  recorded_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (presence <> 'exfoliated' OR tooth_number ~ '^[5-8][1-5]$')
);
CREATE INDEX IF NOT EXISTS idx_tooth_state_events_patient_tooth_date
  ON tooth_state_events(patient_id, tooth_number, effective_date DESC, created_at DESC, id DESC);

-- Access goes through the authenticated Express API, never browser Data API grants.
ALTER TABLE tooth_state_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON tooth_state_events FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON tooth_state_events FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON tooth_state_events FROM authenticated;
  END IF;
END $$;
